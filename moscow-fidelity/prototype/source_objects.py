"""Physical source classes are explicit; map interaction shapes are not meshes.

Audited against retained 2GIS style_flat.json (2026-10-15). Metro_station_house
has no drawing rule; clicking its small disconnected footprint selects a station.
Do not infer a physical building, height or underground level from 'house'.
"""
import re

# The source's traffic-light points were visually checked on 2026-10-16.
# They are map anchors at crossings, not usable pole placements. The project
# explicitly excludes this data from city construction and placement candidates.
EXCLUDED_SOURCE_LAYERS = frozenset({'Traffic_light'})

BUILDING_BODIES = frozenset({
    'Administrative_house', 'Dwelling_house', 'Technical_house', 'School_house',
    'Preschool_house', 'Private_house', 'New_house', 'Floor_plan_house', 'Underground_house',
    'Momrah_building', 'Kiosk', 'Canopy', 'Underpass_entrance',
})
BUILDING_LAYERS = BUILDING_BODIES | frozenset(
    layer + '_roof' for layer in BUILDING_BODIES
    if layer.endswith('_house') or layer == 'Momrah_building'
)
INFORMATION_LAYERS = frozenset({
    'Metro_station_house', 'Subway_stations_scheme_ground',
    'Region', 'Administrative_district', 'Area_of_interest',
    'Shore', 'Parking_area_autogenerated', 'Hospital_place', 'Education_place',
    'Autodrome_place',
})

def exterior_record(properties):
    """Retain interiors in the source archive, outside the outdoor mesh pass."""
    layer=properties.get('db_sublayer','')
    if layer in BUILDING_LAYERS:
        return not properties.get('db_plan_id')
    return not (properties.get('db_plan_id') or layer in EXCLUDED_SOURCE_LAYERS or
                re.match(r'^(Floor|Organization|Office|Hall|Foodcourt|Atrium|Admistrative_area|Technical_area|Subway|Parking_.*underground)',layer))
POLICY = dict(version=2, rule='physical-source-classes-v2',
              physicalBuildingLayers=sorted(BUILDING_LAYERS),
              informationLayers=sorted(INFORMATION_LAYERS),
              unknown='stop object export for an unaudited mesh class',
              information='retain provenance only; never create visible triangles',
              classification='exact source class; never substrings, size, location or object ID')


def source_class(row):
    """Legacy extraction appended the provider ID to source_layer."""
    name = row.get('sourceLayer', '')
    suffix = '_' + str(row.get('sourceBuildingId', ''))
    if suffix != '_' and name.endswith(suffix):
        return name[:-len(suffix)]
    return re.sub(r'_\d+$', '', name)


def role(layer):
    if layer in INFORMATION_LAYERS:
        return 'information'
    if layer in BUILDING_LAYERS:
        return 'physical'
    return 'unclassified'


def object_role(row):
    # Detailed objects have a source GLB, independent of map hit-test footprints.
    if row.get('category') == 'landmark' and row.get('sourceFile'):
        return 'physical'
    if row.get('category') == 'building':
        return role(source_class(row))
    return 'unclassified'


def partition(rows):
    kept, excluded = [], []
    for row in rows:
        decision = object_role(row)
        if decision == 'unclassified':
            raise ValueError(('Unaudited source mesh class', row['id'], source_class(row)))
        (kept if decision == 'physical' else excluded).append(row)
    return kept, excluded


def receipt(excluded):
    return dict(policy=POLICY, excludedObjects=[dict(
        id=r['id'], sourceLayer=source_class(r), sourceBuildingId=r.get('sourceBuildingId'),
        reason='information-only source geometry',
        triangles=r.get('retainedTriangles', r.get('triangles', 0))) for r in excluded])
