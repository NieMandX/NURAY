"""Local derived checkpoints, never a substitute for live source acquisition."""
import pickle
import hashlib
import gzip
import os
import shapely as sh
from collections import defaultdict
from geometry_pickle import dump


def restore_surface_identity(module):
    """Upgrade older checkpoints whose list-length IDs could be reused."""
    rows=getattr(module,'surfaces',[])
    if not rows:return
    by_id=defaultdict(list)
    for s in rows:by_id[s['id']].append(s)
    repeated={key:items for key,items in by_id.items() if len(items)>1}
    next_id=max(int(s['id'].rsplit(':',1)[1]) for s in rows)+1
    for items in repeated.values():
        # Paint witnesses already reference the road ID. Keep that owner when
        # a later land repartition accidentally reused its numeric identifier.
        items.sort(key=lambda s:not s['kind'].startswith('roadbed_'))
        for s in items[1:]:s['id']=f'surface:{next_id}';next_id+=1
    module._surface_id_counter=next_id
    if not repeated:return
    relationships=[]
    for r in module.relationships:
        if r['type'] in ('curb-on-raised-territory','raised-road-boundary'):continue
        if r.get('parent') in repeated:
            candidates=[s for s in repeated[r['parent']] if s['owner']==r.get('sourceObject') and s['kind'].startswith('roadbed_')]
            if len(candidates)!=1:raise ValueError(('Ambiguous retained surface relationship',r))
            r={**r,'parent':candidates[0]['id']}
        relationships.append(r)
    relationships.extend(dict(type='curb-on-raised-territory',parent=s['id'],sourceObject=s['owner'],
        heightM=.1,widthM=.15,evidence='reconstruction-rule') for s in rows if s['kind']=='curb_top')
    module.relationships=relationships
    print('RESTORED UNIQUE SURFACE IDS',sum(len(items)-1 for items in repeated.values()),flush=True)

NAMES=['B','ORIGIN','EXTENT','DATA','SOURCE','DIAG','TILE_KEYS','records','surfaces','relationships',
       'unresolved','groups','shading_flags','dem','demtree','dem_report','road_model',
       'slit_repairs','curb_band','curb_front','curb_report','road_seam_report',
       'protected_road_islands','grade_connections','road_interfaces','interface_report',
       'transition_cut','overpass_profiles','deck_count','source_style','source_owners',
       'style_checks','wall_report','_surface_id_counter']

def save(module,path,inputs):
    if os.environ.get('NURAY_COMPRESS_CHECKPOINTS')=='1' and path.suffix!='.gz':path=path.with_suffix(path.suffix+'.gz')
    temporary=path.with_suffix(path.suffix+'.tmp')
    state={n:getattr(module,n) for n in NAMES if hasattr(module,n)}
    state['_geometryPrecisionVersion']=1
    receipt=module.SOURCE/'sources.json'
    if receipt.exists():state['_checkpointSourceReceiptSha256']=hashlib.sha256(receipt.read_bytes()).hexdigest()
    with (gzip.open(temporary,'wb',compresslevel=1) if path.suffix=='.gz' else temporary.open('wb')) as f:
        dump((state,inputs),f)
    temporary.replace(path)
    # A stale plain sibling must not shadow the newly saved compressed state.
    alternate=path.with_suffix('') if path.suffix=='.gz' else path.with_suffix(path.suffix+'.gz')
    if alternate!=path and alternate.exists():alternate.unlink()
    print('REGION CHECKPOINT',path,flush=True)

def restore(module,path):
    # Only checkpoints generated by this trusted local pipeline are accepted.
    if not path.exists() and path.with_suffix(path.suffix+'.gz').exists():path=path.with_suffix(path.suffix+'.gz')
    with (gzip.open(path,'rb') if path.suffix=='.gz' else path.open('rb')) as f:state,inputs=pickle.load(f)
    expected=state.pop('_checkpointSourceReceiptSha256',None)
    state.pop('_geometryPrecisionVersion',None)
    if expected is not None:
        receipt=state['SOURCE']/'sources.json'
        if hashlib.sha256(receipt.read_bytes()).hexdigest()!=expected:
            raise ValueError('Source receipt changed since the derived checkpoint')
    for key,value in state.items():setattr(module,key,value)
    # GEOS prepared indexes are accelerators, not serialized geometry. Restore
    # the height model's point-in-road index after loading a trusted checkpoint.
    road=getattr(getattr(module,'road_model',None),'road',None)
    if road is not None:sh.prepare(road)
    restore_surface_identity(module)
    return inputs
